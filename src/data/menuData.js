function drinks(rows, category, sizes) {
  return rows.map(([id, name, description, prices, badge]) => ({
    id, name, description, category, badge,
    variants: sizes.map((size, index) => ({ size, label: `${size} мл`, price: prices[index] })),
  }))
}

